#include <iostream>
using namespace std;

int main() {
    cout << "PENGERTIAN KONSEP FIFO\n\n";
    
    cout << "FIFO = First In First Out\n\n";
    
    cout << "Artinya:\n";
    cout << "- Data yang PERTAMA masuk akan PERTAMA keluar\n";
    cout << "- Data yang TERAKHIR masuk akan TERAKHIR keluar\n\n";
    
    cout << "Contoh:\n";
    cout << "Masuk: A, B, C, D\n";
    cout << "Keluar: A, B, C, D\n\n";
    
    cout << "Seperti antrian orang:\n";
    cout << "- Orang pertama datang dilayani duluan\n";
    cout << "- Orang terakhir datang dilayani belakangan\n\n";
    
    cout << "Struktur Data yang menggunakan FIFO: QUEUE\n";
    
    return 0;
}
